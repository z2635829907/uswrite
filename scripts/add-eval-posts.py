def _req(method, path, token=None, body=None):
    url = BASE + path
    data = json.dumps(body).encode("utf-8") if body is not None else None
    req = urllib.request.Request(url, data=data, method=method)
    req.add_header("Content-Type", "application/json")
    if token:
        req.add_header("Authorization", "Bearer " + token)
    try:
        with urllib.request.urlopen(req, timeout=60) as resp:
            return resp.status, json.loads(resp.read().decode("utf-8"))
    except urllib.error.HTTPError as e:
        return e.code, json.loads(e.read().decode("utf-8"))


def login(account, password):
    code, body = _req("POST", "/api/auth/login", body={"account": account, "password": password})
    if code != 200 or not body.get("ok"):
        raise SystemExit(f"登录失败 {account}: {body}")
    return body["token"]


def main():
    demo_token = login("demo", "Demo@2026")
    admin_token = login("admin", "Admin@2026")

    created = []
    for p in POSTS:
        code, body = _req("POST", "/api/posts", token=demo_token,
                          body={"title": p["title"], "content": p["content"],
                                "excerpt": p["excerpt"], "tags": p["tags"],
                                "coverSeed": p["coverSeed"], "category": p["category"],
                                "action": "submit"})
        if code != 200 or not body.get("ok"):
            print(f"[发布失败] {p['title']}: {body}")
            continue
        post = {"id": body["id"], "title": p["title"]}
        created.append(post)
        print(f"[已发布] id={post['id']}  {p['title']}")

    print()
    for post in created:
        code, body = _req("POST", f"/api/admin/posts/{post['id']}/review",
                          token=admin_token, body={"decision": "approve", "reason": ""})
        if code == 200 and body.get("ok"):
            print(f"[已审核通过] id={post['id']}  {post['title']}")
        else:
            print(f"[审核失败] id={post['id']}: {body}")

    print("\n新文章 id 列表:", [p["id"] for p in created])


if __name__ == "__main__":
    main()
